for lang, cat in catalogs.items():
  cat_keys = set(cat.keys())
  diff = en_keys.symmetric_difference(cat_keys)
  if diff:
    print(f"Error in {lang}: key difference with English: {diff}")
    exit(1)
  for k, v in cat.items():
    if not isinstance(v, str) or not v.strip():
      print(f"Empty value in {lang}.{k}")
      exit(1)
    # Check for mojibake
    if re.search(r'(?:à¤|à°|à®|à²|à´|à¦|àª|à¨|à¬)', v):
      print(f"Mojibake found in {lang}.{k}: {v}")
      exit(1)

